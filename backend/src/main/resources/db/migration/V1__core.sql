CREATE TABLE accounts (
 id UUID PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(300) NOT NULL,
 name VARCHAR(100) NOT NULL, role VARCHAR(10) NOT NULL CHECK(role IN ('CLIENT','EXPERT','ADMIN')),
 bio VARCHAR(2000) NOT NULL DEFAULT '', location VARCHAR(150) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories(id VARCHAR(40) PRIMARY KEY,name VARCHAR(80) NOT NULL,description VARCHAR(300) NOT NULL);
