CREATE TABLE experts (
 id UUID PRIMARY KEY, account_id UUID NOT NULL UNIQUE REFERENCES accounts(id),
 category_id VARCHAR(40) NOT NULL REFERENCES categories(id), title VARCHAR(120) NOT NULL,
 bio VARCHAR(3000) NOT NULL, hourly_rate_minor BIGINT NOT NULL CHECK(hourly_rate_minor BETWEEN 100 AND 1000000),
 currency VARCHAR(3) NOT NULL DEFAULT 'USD', years_experience INTEGER NOT NULL CHECK(years_experience BETWEEN 0 AND 80),
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 review_note VARCHAR(1000) NOT NULL DEFAULT '', created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE availability (
 expert_id UUID NOT NULL REFERENCES experts(id), day_of_week INTEGER NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 start_minute INTEGER NOT NULL CHECK(start_minute BETWEEN 0 AND 1439), end_minute INTEGER NOT NULL CHECK(end_minute BETWEEN 1 AND 1440),
 PRIMARY KEY(expert_id,day_of_week), CHECK(end_minute>start_minute)
);
CREATE TABLE bookings (
 id UUID PRIMARY KEY, expert_id UUID NOT NULL REFERENCES experts(id), client_id UUID NOT NULL REFERENCES accounts(id),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL, ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
 amount_minor BIGINT NOT NULL CHECK(amount_minor>0),currency VARCHAR(3) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','CONFIRMED','COMPLETED','CANCELLED')),
 notes VARCHAR(2000) NOT NULL DEFAULT '', request_key UUID NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(client_id,request_key), CHECK(ends_at>starts_at)
);
CREATE INDEX bookings_expert_time ON bookings(expert_id,starts_at,ends_at);
CREATE INDEX bookings_client_time ON bookings(client_id,starts_at,ends_at);
CREATE TABLE payments (
 id UUID PRIMARY KEY, booking_id UUID NOT NULL UNIQUE REFERENCES bookings(id), amount_minor BIGINT NOT NULL CHECK(amount_minor>0),
 currency VARCHAR(3) NOT NULL,status VARCHAR(20) NOT NULL CHECK(status IN ('SIMULATED_PAID','SIMULATED_REFUNDED')),
 provider VARCHAR(20) NOT NULL DEFAULT 'SIMULATOR' CHECK(provider='SIMULATOR'),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE booking_events (
 id UUID PRIMARY KEY, booking_id UUID NOT NULL REFERENCES bookings(id), actor_id UUID NOT NULL REFERENCES accounts(id),
 event_type VARCHAR(40) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE expert_reviews (
 id UUID PRIMARY KEY, expert_id UUID NOT NULL REFERENCES experts(id), actor_id UUID NOT NULL REFERENCES accounts(id),
 decision VARCHAR(20) NOT NULL, note VARCHAR(1000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE reviews (
 id UUID PRIMARY KEY, booking_id UUID NOT NULL UNIQUE REFERENCES bookings(id),rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 comment VARCHAR(2000) NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE messages (
 id UUID PRIMARY KEY,booking_id UUID NOT NULL REFERENCES bookings(id),sender_id UUID NOT NULL REFERENCES accounts(id),
 content VARCHAR(2000) NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX messages_booking_time ON messages(booking_id,created_at);
CREATE TABLE favorites(account_id UUID NOT NULL REFERENCES accounts(id),expert_id UUID NOT NULL REFERENCES experts(id),PRIMARY KEY(account_id,expert_id));
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL, SESSION_ID CHAR(36) NOT NULL, CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INT NOT NULL, EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100), CONSTRAINT SPRING_SESSION_PK PRIMARY KEY(PRIMARY_ID)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL, ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BYTEA NOT NULL,
 CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY(SESSION_PRIMARY_ID,ATTRIBUTE_NAME),
 CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY(SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
