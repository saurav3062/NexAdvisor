CREATE TABLE password_resets (
 token_hash VARCHAR(64) PRIMARY KEY, account_id UUID NOT NULL REFERENCES accounts(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, used BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX password_resets_account ON password_resets(account_id);
CREATE TABLE mail_outbox (
 id UUID PRIMARY KEY, event_key VARCHAR(200) NOT NULL UNIQUE, recipient VARCHAR(254) NOT NULL,
 booking_id UUID REFERENCES bookings(id), notification_kind VARCHAR(20) NOT NULL DEFAULT '',
 subject VARCHAR(200) NOT NULL, body TEXT NOT NULL, sensitive BOOLEAN NOT NULL DEFAULT FALSE,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SENT','FAILED','EXPIRED')),
 attempts INTEGER NOT NULL DEFAULT 0, next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX mail_outbox_pending ON mail_outbox(status,next_attempt_at);
CREATE TABLE booking_meetings (
 booking_id UUID PRIMARY KEY REFERENCES bookings(id), url VARCHAR(2048) NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
